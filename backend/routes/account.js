// User data export (GDPR art. 20 - the right to data portability).
// The app processes health data (weight, body composition, activity, sleep) from
// Oura/Withings/Apple Health/Google Fit - a special category under GDPR art. 9 - so the
// user must be able to download their own data without asking an administrator.
// Passwords and secrets (password_hash, totp_secret, OAuth tokens) are deliberately
// EXCLUDED from the export: they are account security credentials, not 'personal data to
// be ported'.
router.get('/api/user/export', async (req, res) => {
  try {
    const userId = req.user.id;
    const user = await db.get(`
      SELECT username, email, first_name, last_name, role, created_at
      FROM users WHERE id = ?
    `, [userId]);
    if (!user) {
      return res.status(404).json({ error: 'Użytkownik nie istnieje.' });
    }

    const [settings, meals, healthMetrics, bodyMeasurements, workouts] = await Promise.all([
      db.all(`SELECT key, value FROM settings WHERE user_id = ?`, [userId]),
      // B-S1: skipping image_base64 prevents an OOM during a GDPR export on large accounts
      db.all(`SELECT id, user_id, date, timestamp, raw_text, calories, protein, carbs, fat, fiber, sugar, sodium, health_rating, analysis_json FROM meals WHERE user_id = ? ORDER BY timestamp`, [userId]),
      db.all(`SELECT * FROM health_metrics WHERE user_id = ? ORDER BY date`, [userId]),
      db.all(`SELECT * FROM body_measurements WHERE user_id = ? ORDER BY date`, [userId]),
      db.all(`SELECT * FROM apple_health_workouts WHERE user_id = ? ORDER BY date`, [userId])
    ]);

      // OAuth secrets and credentials (oura_client_secret, withings_client_secret,
      // and so on) are masked here as well: a data-portability export should not reveal
      // integration secrets in a file the user may save somewhere or forward on.
    const maskedSettings = {};
    settings.forEach(r => {
      maskedSettings[r.key] = maskSecretValue(r.key, r.value, USER_SECRET_SETTING_KEYS);
    });

    res.setHeader('Content-Disposition', 'attachment; filename="dietetyk-ai-eksport-danych.json"');
    res.json({
      exported_at: new Date().toISOString(),
      profile: {
        username: user.username,
        email: user.email,
        first_name: user.first_name,
        last_name: user.last_name,
        role: user.role,
        created_at: user.created_at
      },
      settings: maskedSettings,
      meals,
      health_metrics: healthMetrics,
      body_measurements: bodyMeasurements,
      apple_health_workouts: workouts
    });
  } catch (err) {
    console.error('[EXPORT ERROR]', err);
    res.status(500).json({ error: 'Błąd eksportu danych.' });
  }
});

