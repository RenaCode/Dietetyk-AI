// Simple email format validation (not full RFC 5322 - this is enough to reject obviously
// invalid values written straight to the database or used as a Mailgun recipient).
const EMAIL_REGEX = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
// Time format HH:MM (00-23 : 00-59), used when scheduling summary delivery.
const TIME_REGEX = /^([01]\d|2[0-3]):([0-5]\d)$/;
// sync_token validation (round 15 audit fix): the token is generated by default as
// 'sync_' + 24 random hex bytes (see routes/auth.js and admin.js), but the endpoint below
// lets a user overwrite it with a value of their own. sync_token is the ONLY secret
// authorising the unauthenticated Apple Health webhook
// (POST /api/integrations/apple-health/:syncToken, see routes/appleHealth.js and
// server.js - that endpoint deliberately bypasses requireAuth). Without a minimum length
// and format a user could set a token such as 'abc', which in practice would make the
// webhook publicly guessable and hijackable.
const SYNC_TOKEN_REGEX = /^[A-Za-z0-9_-]{16,128}$/;
// Length limit for the physique goal description - without it nothing bounded the size of
// the text that later goes into the Gemini prompt (see dashboard.js and chat.js),
// analogicznie do MAX_CHAT_MESSAGE_LENGTH w chat.js.
const MAX_BODY_GOAL_TEXT_LENGTH = 1000;
// Size limit for the physique goal photo as base64 (about 3 MB encoded, roughly 2.2 MB of
// real file) - the photo is compressed and scaled on the frontend (see Settings.jsx), but
// this is the only real protection against someone posting straight to the API.
const MAX_BODY_GOAL_PHOTO_LENGTH = 4 * 1024 * 1024;
// Avatar size limit - same reasoning as the physique goal photo above. The
// POST /api/user/profile endpoint used to store `avatar` with NO size validation at all;
// the only protection was the global express.json({limit:'20mb'}) in server.js.
const MAX_AVATAR_BASE64_LENGTH = 3 * 1024 * 1024;
// Length limit for the location query (Settings -> weather location) - the query goes to
// the external Open-Meteo geocoder, so bound its size rather than passing an arbitrarily
// long string through (see GET /api/settings/geocode-location below).
const MAX_LOCATION_QUERY_LENGTH = 100;

router.get('/api/settings', async (req, res) => {
  try {
    const rows = await db.all(`SELECT * FROM settings WHERE user_id = ?`, [req.user.id]);
    const user = await db.get(`SELECT sync_token FROM users WHERE id = ?`, [req.user.id]);
    const settings = {
      sync_token: user ? user.sync_token : ''
    };
    rows.forEach(r => {
      if (USER_SECRET_SETTING_KEYS.includes(r.key) && r.value) {
        settings[r.key] = maskSecretValue(r.key, r.value, USER_SECRET_SETTING_KEYS);
      } else if (r.value === '') {
      // NOTE: Number('') === 0 and isNaN('') === false - so without this exception an empty
      // string would be converted to the number 0 here. That was a real bug:
      // withings_client_id/oura_client_id stored as '' (through an unintended empty save of
      // the whole settings form, for instance) came back from this endpoint as 0. In JS 0 is
      // a number, so the code building the OAuth URL - which only checks `if (!clientId)` -
      // rejected it; but the string "0", once saved back through POST, is no longer falsy and
      // passed through, producing client_id=0 in the Withings/Oura authorisation URL.
        settings[r.key] = '';
      } else {
        settings[r.key] = isNaN(r.value) ? r.value : Number(r.value);
      }
    });
    // Note: there is NO fallback to global environment variables (OURA_CLIENT_ID/SECRET,
    // WITHINGS_CLIENT_ID/SECRET) - every user, admin included, must configure their own Oura
    // and Withings application credentials. That way a new user never connects through
    // another user's OAuth application.
    res.json(settings);
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Błąd pobierania ustawień.' });
  }
});

// 6. Saving settings and daily targets
// Integration credential fields must never be overwritten with empty or zero values,
// because that breaks OAuth (see the comment on GET /api/settings above). Every settings
// save from the frontend sends the WHOLE form state, not just the changed field, so saving
// only the calorie targets could otherwise
// accidentally 'clear' the Client ID/Secret when the form state happened to hold them
// empty or unset at that moment.
const CREDENTIAL_KEYS = ['oura_client_id', 'oura_client_secret', 'withings_client_id', 'withings_client_secret'];

router.post('/api/settings', async (req, res) => {
  const settings = req.body; // keys and values
  try {
    for (const [key, val] of Object.entries(settings)) {
      if (key === 'sync_token') continue; // Pole tylko do odczytu
      if (isMaskedSecretWrite(key, val, USER_SECRET_SETTING_KEYS)) {
        continue; // skip updating a secret when the mask was sent back
      }
      if (CREDENTIAL_KEYS.includes(key) && (val === '' || val === null || val === undefined || val === 0)) {
        continue; // never store an empty/zero credential value - see the comment above
      }
      // Sekrety (gemini_api_key, oura/withings_client_secret) trzymamy w bazie
      // encrypted (see utils/encryption.js) - encrypt() is a no-op for the remaining,
      // non-secret settings keys.
      const storedValue = USER_SECRET_SETTING_KEYS.includes(key) ? encrypt(String(val)) : String(val);
      await db.run(`
        INSERT INTO settings (user_id, key, value)
        VALUES (?, ?, ?)
        ON CONFLICT(user_id, key) DO UPDATE SET value = excluded.value
      `, [req.user.id, key, storedValue]);
    }
    res.json({ success: true, message: 'Ustawienia zostały zaktualizowane.' });
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Błąd zapisu ustawień.' });
  }
});

// Location lookup for the 'Location' field in Settings (the weather context injected into
// AI prompts - see utils/weatherContext.js). Returns a list of candidates for the frontend
// to choose from (Open-Meteo Geocoding, no API key required) - place names are often
// ambiguous, so we do NOT auto-select the first result. Choosing the location itself (POST)
// goes through the existing settings endpoint, since weather_location_label and friends are
// ordinary keys in the settings table - this endpoint only searches and stores nothing.
router.get('/api/settings/geocode-location', async (req, res) => {
  const query = typeof req.query.q === 'string' ? req.query.q.trim() : '';
  if (!query) {
    return res.status(400).json({ error: 'Podaj nazwę miejscowości.' });
  }
  if (query.length > MAX_LOCATION_QUERY_LENGTH) {
    return res.status(400).json({ error: `Zapytanie jest zbyt długie (maks. ${MAX_LOCATION_QUERY_LENGTH} znaków).` });
  }
  try {
    const results = await geocodeLocation(query);
    res.json({ results });
  } catch (err) {
    console.error('[GEOCODING ERROR]', err);
    res.status(502).json({ error: 'Błąd wyszukiwania lokalizacji (usługa geokodowania jest chwilowo niedostępna).' });
  }
});

